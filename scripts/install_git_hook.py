"""Install the SecretLeak pre-commit hook into a local Git repository.

Usage:
    python scripts/install_git_hook.py [repo_path] [--min-severity high] [--force]

What the hook does:
* Scans the content staged for commit (not unrelated uncommitted files).
* Prints masked previews only — full secrets never hit your terminal.
* Exits nonzero (blocks the commit) when findings at or above the configured
  severity are detected; scan *errors* fail open so a broken scanner never
  traps your work.

Impact and honesty notes:
* An existing pre-commit hook is NEVER overwritten without --force.
* Client-side hooks are advisory: `git commit --no-verify` bypasses them, and
  clones do not receive hooks. They are not a substitute for server-side
  secret scanning.
"""

from __future__ import annotations

import argparse
import stat
import sys
from pathlib import Path

BACKEND_DIR = Path(__file__).resolve().parents[1] / "backend"
sys.path.insert(0, str(BACKEND_DIR))

from app.detectors.rules import SEVERITY_ORDER  # noqa: E402
from app.services.path_safety import PathSafetyError, validate_repository_path  # noqa: E402

MARKER = "# SecretLeak managed pre-commit hook"


def build_hook_script(python_bin: Path, backend_dir: Path, min_severity: str) -> str:
    return f"""#!/bin/sh
{MARKER}
# Generated by scripts/install_git_hook.py — do not edit; reinstall to update.
# Scans STAGED content only. Prints masked values only. Blocking severity: {min_severity}
# Hooks are advisory: `git commit --no-verify` bypasses them.

PYTHON_BIN="{python_bin.as_posix()}"
BACKEND_DIR="{backend_dir.as_posix()}"

if [ ! -f "$BACKEND_DIR/app/cli_scan.py" ]; then
  echo "[secretleak] backend not found at $BACKEND_DIR — skipping scan (fail-open)."
  exit 0
fi

if ! "$PYTHON_BIN" -c "import sys" >/dev/null 2>&1; then
  echo "[secretleak] python not available — skipping scan (fail-open)."
  exit 0
fi

"$PYTHON_BIN" "$BACKEND_DIR/app/cli_scan.py" --staged --min-severity {min_severity}
status=$?
# 0 = clean (or scan error), 2 = blocking findings; anything else fails open.
if [ "$status" -eq 2 ]; then
  exit 2
fi
exit 0
"""


def install(repo: Path, min_severity: str, force: bool) -> int:
    hook_path = repo / ".git" / "hooks" / "pre-commit"
    hook_path.parent.mkdir(parents=True, exist_ok=True)

    if hook_path.exists():
        existing = hook_path.read_text(encoding="utf-8", errors="replace")
        if MARKER not in existing and not force:
            print(f"Refusing to overwrite an existing hook: {hook_path}")
            print("Re-run with --force to replace it (the old hook will be lost), "
                  "or merge manually.")
            return 1
        if MARKER in existing:
            print("Replacing previous SecretLeak hook.")
        elif force:
            backup = hook_path.with_suffix(".pre-secretleak-backup")
            backup.write_text(existing, encoding="utf-8")
            print(f"Backed up existing hook to {backup}")

    script = build_hook_script(Path(sys.executable), BACKEND_DIR, min_severity)
    hook_path.write_text(script, encoding="utf-8", newline="\n")
    try:
        hook_path.chmod(hook_path.stat().st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)
    except OSError:
        pass  # Windows: git for windows executes hooks via sh regardless

    print(f"Installed SecretLeak pre-commit hook: {hook_path}")
    print(f"  - scans staged content only; blocks commits with findings >= {min_severity}")
    print("  - change the threshold by reinstalling with --min-severity")
    print("  - remember: hooks are advisory and can be bypassed with --no-verify")
    return 0


def uninstall(repo: Path, force: bool) -> int:
    hook_path = repo / ".git" / "hooks" / "pre-commit"
    if not hook_path.exists():
        print(f"No pre-commit hook found at {hook_path}; nothing to do.")
        return 0
    content = hook_path.read_text(encoding="utf-8", errors="replace")
    if MARKER not in content and not force:
        print(f"The pre-commit hook at {hook_path} was not created by SecretLeak; "
              "leaving it untouched (use --force to delete anyway).")
        return 1
    hook_path.unlink()
    print(f"Removed SecretLeak pre-commit hook: {hook_path}")
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("command", choices=["install", "uninstall"])
    parser.add_argument("repo_path", nargs="?", default=".")
    parser.add_argument("--min-severity", choices=list(SEVERITY_ORDER), default="high")
    parser.add_argument("--force", action="store_true")
    args = parser.parse_args(argv)

    try:
        repo = validate_repository_path(args.repo_path)
    except PathSafetyError as exc:
        print(f"error: {exc}")
        return 1
    if not (repo / ".git").exists():
        print(f"error: {repo} is not a Git repository (no .git directory).")
        return 1

    if args.command == "install":
        return install(repo, args.min_severity, args.force)
    return uninstall(repo, args.force)


if __name__ == "__main__":
    raise SystemExit(main())
